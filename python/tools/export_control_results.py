#!/usr/bin/env python3
"""Generate all new Part VI numerical teaching tables from executed JSON."""
from pathlib import Path
import json,shutil
import numpy as np
ROOT=Path(__file__).resolve().parents[2];COMMON=ROOT/'latex/common'

def read(stem):
    paths=list((ROOT/'python').glob(f'[23]*/data/{stem}_results.json'))
    if len(paths)!=1:raise FileNotFoundError(f'Execute {stem} before exporting ({len(paths)} results files).')
    return json.loads(paths[0].read_text())['metrics']
def med(rows,key):return float(np.median([r[key] for r in rows]))
def fmt(x,d=2):
    if x is None:return '--'
    return f'{x:.{d}f}'
def table(name,rows):return '\\def\\'+name+'{%\n'+'\n'.join(' & '.join(map(str,r))+r' \\' for r in rows)+'\n}\n'
def macro(name,value):return '\\def\\'+name+'{'+str(value)+'}\n'

def main():
    out='% Generated by python/tools/export_control_results.py; values from results JSON.\n'
    koop=read('koop_hybrid_models');rows=[]
    for name in ('plain lift','sparse library','lift + residual'):
        r=[a for a in koop['rows'] if a['name']==name]
        rows.append([name,fmt(med(r,'observables'),0),fmt(100*med(r,'one_step_relative_increment')),fmt(np.median([a['nominal']['cost'] for a in r]),1),fmt(np.median([a['nominal']['solve_median_ms'] for a in r]))])
    out+=table('controlkooprows',rows)
    out+=macro('controlSelectedNames',', '.join(koop['selection']['selected']['names']).replace('_',r'\_').replace('^3',r'\textasciicircum3'))
    out+=macro('controlSelectedCount',len(koop['selection']['selected']['indices']))
    drift=koop['drift'];rows=[]
    for key in ('Du','Dv','Dr','Xuu','Yvv','Nrr'):
        value=np.median([r['coefficients'][key] for r in drift['pinn']]);truth=drift['truth'][key]
        rows.append([key,fmt(truth),fmt(value),fmt(100*(value/truth-1))])
    out+=table('controlpinnrows',rows)
    out+=macro('controlDriftOldError',fmt(drift['old_lift']['one_step_rmse'],4))
    out+=macro('controlDriftRefitError',fmt(drift['edmdc_refit']['one_step_rmse'],4))
    out+=macro('controlDriftPINNError',fmt(med(drift['pinn'],'one_step_rmse'),4))
    rl=read('rl_learned_twins')['rows'];rows=[]
    for name in ('exact','costa','dnn'):
        r=[a for a in rl if a['twin']==name]
        rows.append([name,fmt(med(r,'steps_per_second')/1000,0),fmt(np.median([a['twin_evaluation']['cost'] for a in r])/1000,2),fmt(np.median([a['true_plant']['cost'] for a in r])/1000,2),fmt(np.median([a['shifted']['cost'] for a in r])/1000,2),fmt(med(r,'training_seconds'),1)])
    out+=table('controltwinrows',rows)
    safety=read('safe_hybrid_bounds');rows=[]
    for name in ('dmdc','sindy','dnn'):
        a,b=safety['domain']['1'][name],safety['domain']['4'][name]
        rows.append([name,fmt(a['rmse'],4),fmt(b['rmse'],4),fmt(b['rmse']/a['rmse'],1),fmt(b['bound_blowup'],1),fmt(100*b['bound_coverage'],1)])
    out+=table('controldomainrows',rows)
    out+=table('controlensemblerows',[[name]+[fmt(100*safety['ensemble'][s][name]['simultaneous_coverage'],1) for s in ('1','2','4')] for name in ('dnn','costa')])
    rows=[]
    for name in ('linear','sindy','costa'):
        r=[a for a in safety['tubes'] if a['model']==name];ok=[a['tightened'] for a in r if a['tightened']['feasible_design']]
        rows.append([name,fmt(np.median([a['bound']['delta'][-1] for a in r]),3),fmt(np.median([a['nominal']['cost'] for a in r]),1),fmt(med(ok,'cost'),1) if ok else '--',fmt(med(ok,'state_violation_worst_m'),3) if ok else '--',f'{len(ok)}/{len(r)}'])
    out+=table('controltuberows',rows)
    shield=read('safe_shielding')['rows'];rows=[]
    for name in ('dnn','sindy'):
        r=[a for a in shield if a['model']==name]
        rows.append([name,fmt(np.median([a['unshielded']['violation_count'] for a in r]),0),fmt(np.median([a['shielded']['violation_count'] for a in r]),0),fmt(100*np.median([a['shielded']['shield_fraction'] for a in r]),1),fmt(np.median([a['shielded']['distance_m'] for a in r]),1),fmt(100*np.median([a['slow_mission']['shield_fraction'] for a in r]),1)])
    out+=table('controlshieldrows',rows)
    field=read('mpc_field_models');rows=[]
    for name in dict.fromkeys(r['model'] for r in field['rows']):
        r=[a for a in field['rows'] if a['model']==name]
        rows.append([name,f"{med(r,'one_step_rmse'):.2g}",fmt(med(r,'cost_penalty_percent'),3),fmt(med(r,'solve_median_ms')),fmt(med(r,'solve_max_ms')),fmt(med(r,'deadline_misses'),0)])
    out+=table('controlfieldrows',rows)
    out+=table('controlsensorrows',[[a['sensors'],fmt(a['cost'],5),fmt(a['solve_median_ms'])] for a in field['sparse_sensors']])
    surge=read('mpc_surge_horizon')['rows']
    out+=table('controlsurgerows',[[name,fmt(np.median([r[key]['cost'] for r in surge])),fmt(np.median([r[key]['solve_median_ms'] for r in surge]))] for name,key in [('Exact horizon','exact'),('DeepONet','learned')]])
    out+=macro('controlSurgeTest',fmt(med(surge,'rollout_20_rmse'),3))+macro('controlSurgeShift',fmt(med(surge,'outside_family_rmse'),3))
    old=read('rl_vs_mpc')
    out+=macro('controlRLspeedup',fmt(old['SPEEDUP'],0))+macro('controlRLwall',fmt(old['WALL'],1))+macro('controlRLthroughput',fmt(old['TWIN_STEPS_PER_S'],0))
    timing=read('mpc_horizon_realtime');ms=np.array(timing['ms'])
    out+=macro('controlMPCmedian',fmt(np.median(ms),3))+macro('controlMPCp',fmt(np.quantile(ms,.95),3))+macro('controlMPCmax',fmt(ms.max(),3))
    out+=macro('controlMPClongmedian',fmt(timing['d_60']['med'],2))+macro('controlMPClongmax',fmt(timing['d_60']['mx'],1))
    lift=read('koop_lifting');mpc=read('koop_mpc')
    out+=macro('controlLiftRadius',fmt(max(abs(np.linalg.eigvals(lift['A_k']))),4))
    out+=macro('controlMPCLiftRadius',fmt(max(abs(np.linalg.eigvals(mpc['A_k']))),3))
    shared=read('vessel_loop')['models']
    failures=[]
    for name,r in shared.items():
        a,b=r['nominal'],r['shifted']
        finding='large tracking error' if a['position_rms_m']>1 else ('shift amplification' if b['position_rms_m']>2*a['position_rms_m'] else 'tracked this task')
        failures.append([name,fmt(a['position_rms_m'],3),fmt(b['position_rms_m'],3),fmt(100*a['outside_domain_fraction'],0),finding])
    out+=table('controlfailurerows',failures)
    COMMON.joinpath('controlresults.tex').write_text(out)
    dest=COMMON/'figures';dest.mkdir(exist_ok=True)
    for variant in ('','_dark'):
        source=ROOT/f'python/27-model-predictive-control/figures/vessel_loop_models{variant}.png'
        shutil.copy2(source,dest/source.name)
    print('Generated controlresults.tex and shared figure copies from executed results.')
if __name__=='__main__':main()
